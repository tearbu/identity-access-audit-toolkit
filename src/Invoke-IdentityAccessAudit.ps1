<#
.SYNOPSIS
    Runs all three identity audits and writes one combined report.

.DESCRIPTION
    Orchestrator for the Identity & Access Audit Toolkit. Runs:
      1. Stale account audit       (Get-StaleAccountAudit.ps1)
      2. MFA coverage audit        (Get-MfaCoverageAudit.ps1)
      3. Privileged group audit    (Get-PrivilegedGroupAudit.ps1)

    Writes per-audit CSVs plus a single Markdown summary (audit-summary.md)
    into -OutputFolder. That summary is the artifact you hand to a reviewer:
    counts first, then the findings that need an owner and a decision.

.EXAMPLE
    .\Invoke-IdentityAccessAudit.ps1 -UseSampleData

.EXAMPLE
    .\Invoke-IdentityAccessAudit.ps1 -OutputFolder .\reports\2026-Q4

.NOTES
    Author : Araf Abubakar
    Part of the Identity & Access Audit Toolkit. Demo data is fictional.
#>
[CmdletBinding()]
param(
    [switch]$UseSampleData,
    [string]$OutputFolder = (Join-Path $PSScriptRoot '..\output')
)

$ErrorActionPreference = 'Stop'
New-Item -ItemType Directory -Path $OutputFolder -Force | Out-Null

$src = $PSScriptRoot
$common = @{}
if ($UseSampleData) { $common['UseSampleData'] = $true }

Write-Host "Running stale account audit..."
$stale = & (Join-Path $src 'Get-StaleAccountAudit.ps1') @common -OutputPath (Join-Path $OutputFolder 'stale-accounts.csv')

Write-Host "Running MFA coverage audit..."
$mfa = & (Join-Path $src 'Get-MfaCoverageAudit.ps1') @common -OutputPath (Join-Path $OutputFolder 'mfa-coverage.csv')

Write-Host "Running privileged group audit..."
$priv = & (Join-Path $src 'Get-PrivilegedGroupAudit.ps1') @common -OutputPath (Join-Path $OutputFolder 'privileged-groups.csv')

$mode = if ($UseSampleData) { 'Sample data (fictional contoso-demo tenant)' } else { 'Live Microsoft Graph tenant' }
$lines = @(
    '# Identity & Access Audit - Summary'
    ''
    "Generated: $(Get-Date -Format 'yyyy-MM-dd HH:mm')  |  Mode: $mode"
    ''
    '## Headline numbers'
    ''
    "| Audit | Findings |"
    "| --- | --- |"
    "| Stale / never-signed-in enabled accounts | $(@($stale).Count) |"
    "| Accounts without MFA (admin/service gaps first) | $(@($mfa).Count) |"
    "| Privileged group findings | $(@($priv).Count) |"
    ''
    '## Stale accounts'
    ''
)
foreach ($f in @($stale)) { $lines += "- **$($f.DisplayName)** ($($f.UserPrincipalName)) - $($f.Status), $($f.DaysInactive) days inactive. Action: $($f.RecommendedAction)." }
$lines += @('', '## MFA gaps', '')
foreach ($f in @($mfa)) { $lines += "- **$($f.DisplayName)** ($($f.UserPrincipalName)) - Severity $($f.Severity). Action: $($f.RecommendedAction)." }
$lines += @('', '## Privileged group findings', '')
foreach ($f in @($priv)) { $lines += "- **$($f.GroupName)** / $($f.Member) - $($f.Finding) (Severity $($f.Severity)). Action: $($f.RecommendedAction)." }
$lines += @('', '---', 'Generated by the Identity & Access Audit Toolkit. Verify each finding with the account owner before disabling or removing access.')

$summaryPath = Join-Path $OutputFolder 'audit-summary.md'
$lines | Set-Content -Path $summaryPath -Encoding UTF8

Write-Host ""
Write-Host "Done. Summary report: $summaryPath"
